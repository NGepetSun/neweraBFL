const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36";

async function checkChannel(ch) {
  const url = `https://www.youtube.com/channel/${ch.id}/live`;
  try {
    const controller = new AbortController();
    const t = setTimeout(() => controller.abort(), 5000);
    const res = await fetch(url, {
      headers: {
        "User-Agent": UA,
        "Accept-Language": "en-US,en;q=0.9",
      },
      signal: controller.signal,
      redirect: "follow",
    });
    clearTimeout(t);

    if (!res.ok) {
      return { id: ch.id, name: ch.name, isLive: false, videoId: null, title: null };
    }

    const html = await res.text();

    const isLive = /"isLiveNow":true|"isLive":true/.test(html);

    let videoId = null;
    let m = html.match(/<link rel="canonical" href="https:\/\/www\.youtube\.com\/watch\?v=([a-zA-Z0-9_-]{11})"/);
    if (!m) m = html.match(/"canonicalBaseUrl":"\/watch\?v=([a-zA-Z0-9_-]{11})"/);
    if (m) videoId = m[1];

    let title = null;
    const tm = html.match(/<meta name="title" content="([^"]*)"/);
    if (tm) title = tm[1];

    return {
      id: ch.id,
      name: ch.name,
      isLive: isLive && !!videoId,
      videoId: isLive ? videoId : null,
      title: isLive ? title : null,
    };
  } catch (e) {
    return { id: ch.id, name: ch.name, isLive: false, videoId: null, title: null, error: String(e.message || e) };
  }
}

// Jalankan pengecekan dengan concurrency terbatas agar tidak membebani
// konejsi server / kena rate-limit YouTube.
async function checkAll(channels, concurrency = 10) {
  const results = {};
  let idx = 0;

  async function worker() {
    while (idx < channels.length) {
      const i = idx++;
      const ch = channels[i];
      const r = await checkChannel(ch);
      results[ch.id] = r;
    }
  }

  const workers = Array.from({ length: Math.min(concurrency, channels.length) }, () => worker());
  await Promise.all(workers);
  return results;
}

module.exports = async function handler(req, res) {
  res.setHeader("Access-Control-Allow-Origin", "*");
  res.setHeader("Cache-Control", "s-maxage=60, stale-while-revalidate=120");

  const now = Date.now();
  const force = req.query.refresh === "1";

  if (!force && now - cache.timestamp < CACHE_TTL && Object.keys(cache.data).length > 0) {
    return res.status(200).json({
      cached: true,
      updatedAt: cache.timestamp,
      channels: cache.data,
    });
  }

  try {
    const data = await checkAll(CHANNELS, 10);
    cache = { timestamp: now, data };
    return res.status(200).json({
      cached: false,
      updatedAt: cache.timestamp,
      channels: cache.data,
    });
  } catch (e) {
    // Kalau gagal total tapi masih ada cache lama, kirim cache lama
    if (Object.keys(cache.data).length > 0) {
      return res.status(200).json({
        cached: true,
        stale: true,
        updatedAt: cache.timestamp,
        channels: cache.data,
      });
    }
    return res.status(500).json({ error: String(e.message || e) });
  }
}
